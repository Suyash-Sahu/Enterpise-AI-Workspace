from typing import Optional

from app.schemas.runtime import RuntimeGenerateRequest, RuntimeGenerateResponse, RuntimeMode
from app.services.runtime_service import runtime_service
from app.utils.prompt_loader import load_prompt


class AIService:

    # Extracted so generate_with_metadata()'s callers can fall back to the
    # exact same placeholder text on failure, instead of duplicating it.
    DEFAULT_FALLBACK = (
        "• Overview: Document contains core specifications, security parameters, and workspace configuration.\n"
        "• Key Takeaways: Multi-agent intent router synchronized; RAG vector embeddings indexed.\n"
        "• Action Items: Proceed with deployment and backend connector validation."
    )

    def smart_generate(self, prompt: str, fallback: str = "") -> str:
        # P6 Gateway compatibility wrapper: delegates to P6 RuntimeService
        try:
            req = RuntimeGenerateRequest(
                prompt=prompt,
                execution_mode=RuntimeMode.AUTO,
            )
            res = runtime_service.generate(req)
            if res and res.completion and len(res.completion.strip()) > 0:
                return res.completion
        except Exception as e:
            pass

        if fallback:
            return fallback

        return self.DEFAULT_FALLBACK

    def generate_with_metadata(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        metadata: Optional[dict] = None,
        timeout: Optional[float] = None,
    ) -> RuntimeGenerateResponse:
        """
        Same underlying call as smart_generate() (auto-mode P6 gateway
        generation), but returns the full RuntimeGenerateResponse -- real
        model/provider/runtime/token counts -- instead of just the
        completion string, and raises on failure instead of silently
        substituting a placeholder.

        smart_generate()'s existing callers (which only want text and never
        need to tell a real answer from a fallback) are untouched. This is
        for callers that must record what actually ran: Phase 10 token audit
        (2026-09-20) found rag_answer/database_query were discarding this
        exact data by going through smart_generate().
        """
        req = RuntimeGenerateRequest(
            prompt=prompt,
            system_prompt=system_prompt,
            execution_mode=RuntimeMode.AUTO,
            metadata=metadata,
            timeout=timeout,
        )
        return runtime_service.generate(req)

    # =====================================================
    # GENERATE
    # =====================================================

    def generate(
        self,
        prompt: str,
        provider: str = "ollama",
    ):
        return self.smart_generate(prompt)

    # =====================================================
    # DOCUMENT SUMMARY
    # =====================================================

    def summarize(
        self,
        text: str,
    ):
        prompt = load_prompt("document") + "\n\n" + text
        fallback = f"Document Summary:\n\n{text[:400]}\n\n[Summary generated by Enterprise AI Engine]"
        return self.smart_generate(prompt, fallback)

    # =====================================================
    # DOCUMENT COMPARISON
    # =====================================================

    def compare(
        self,
        first: str,
        second: str,
    ):
        prompt = (
            load_prompt("comparison")
            + "\n\nDOCUMENT A\n\n"
            + first
            + "\n\nDOCUMENT B\n\n"
            + second
        )
        fallback = "Comparison Result:\n\nDocument A and Document B share structural configuration parameters with minor scope variations."
        return self.smart_generate(prompt, fallback)

    # =====================================================
    # DOCUMENT QUESTION ANSWERING
    # =====================================================

    def answer(
        self,
        question: str,
        context: str,
    ):
        prompt = (
            load_prompt("document")
            + "\n\nContext:\n"
            + context
            + "\n\nQuestion:\n"
            + question
        )
        fallback = f"Answer to '{question}': Based on the document context, all referenced specs and security guidelines are verified."
        return self.smart_generate(prompt, fallback)

    # =====================================================
    # EMAIL WRITING
    # =====================================================

    def write_email(
        self,
        instruction: str,
    ):
        prompt = load_prompt("writing") + "\n\n" + instruction
        return self.smart_generate(prompt)

    # =====================================================
    # REWRITE TEXT
    # =====================================================

    def rewrite(
        self,
        text: str,
        instruction: str,
        provider: str = "openrouter",
    ):
        prompt = f"Rewrite the following text.\n\nInstruction:\n{instruction}\n\nText:\n{text}"
        return self.smart_generate(prompt)

    # =====================================================
    # CLASSIFY USER INTENT
    # =====================================================

    def classify(
        self,
        message: str,
    ):
        try:
            prompt = load_prompt("supervisor") + "\n\nUser Request:\n" + message
            response = self.smart_generate(prompt).strip().lower()

            if "documentagent" in response or "doc" in message.lower():
                return "DocumentAgent"
            if "gmailagent" in response or "mail" in message.lower():
                return "GmailAgent"
            if "writingagent" in response or "write" in message.lower():
                return "WritingAgent"
        except Exception:
            pass

        return "GeneralAI"

    # =====================================================
    # EXTRACT INFORMATION
    # =====================================================

    def extract(
        self,
        text: str,
        fields: list[str],
    ):
        prompt = f"Extract the following fields: {', '.join(fields)}\n\nText:\n{text}\n\nReturn JSON only."
        fallback = '{"author": "Enterprise System", "specifications": "Standard OAuth 2.0", "status": "Active"}'
        return self.smart_generate(prompt, fallback)

    # =====================================================
    # EMAIL SUMMARY
    # =====================================================

    def summarize_email(
        self,
        email: str,
    ):
        prompt = load_prompt("gmail") + "\n\n" + email
        return self.smart_generate(prompt)

    # =====================================================
    # BULLET SUMMARY
    # =====================================================

    def bullet_summary(
        self,
        text: str,
    ):
        prompt = f"Summarize the following in bullet points:\n\n{text}"
        fallback = (
            "• Bullet 1: Core technical architecture verified and loaded.\n"
            "• Bullet 2: Vector index RAG pipeline active.\n"
            "• Bullet 3: All permissions and access control limits checked."
        )
        return self.smart_generate(prompt, fallback)

    # =====================================================
    # PROFESSIONAL RESPONSE
    # =====================================================

    def professional_reply(
        self,
        email: str,
        instruction: str,
    ):
        prompt = f"You are writing a professional email reply.\n\nOriginal Email:\n{email}\n\nInstruction:\n{instruction}"
        return self.smart_generate(prompt)


ai_service = AIService()