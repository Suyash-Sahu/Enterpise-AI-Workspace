"use client";

import { useState } from "react";
import { toast } from "sonner";
import PageHeader from "@/components/shared/PageHeader";
import SearchInput from "@/components/shared/SearchInput";
import { Button } from "@/components/ui/button";
import { useTasks } from "@/hooks/useProjects";
import { CheckCircle2, Clock, AlertCircle, Plus, Filter, User, Tag, ArrowUpRight } from "lucide-react";

export default function TasksPage() {
    const [search, setSearch] = useState("");
    const [statusFilter, setStatusFilter] = useState<string>("all");
    const { data: tasks, isLoading } = useTasks();

    const filtered = (tasks || []).filter((t) => {
        const matchesSearch = t.title.toLowerCase().includes(search.toLowerCase());
        const matchesStatus = statusFilter === "all" || t.status.toLowerCase() === statusFilter.toLowerCase();
        return matchesSearch && matchesStatus;
    });

    const getPriorityBadge = (priority: string) => {
        switch (priority.toLowerCase()) {
            case "critical":
                return "bg-destructive/10 text-destructive border-destructive/20";
            case "high":
                return "bg-warning/10 text-warning border-warning/20";
            case "medium":
                return "bg-info/10 text-info border-info/20";
            default:
                return "bg-muted text-muted-foreground border-border";
        }
    };

    return (
        <div className="space-y-6">
            <PageHeader
                title="Tasks & Assignments"
                description="View and track workspace action items generated by team members and AI Agents."
                breadcrumbs={[{ label: "Workspace" }, { label: "Tasks" }]}
                actions={
                    <Button
                        size="sm"
                        onClick={() => toast("Task creation isn’t available yet")}
                    >
                        <Plus aria-hidden />
                        Create task
                    </Button>
                }
            />

            {/* Search & Status Filters */}
            <div className="flex flex-col sm:flex-row items-center justify-between gap-4 border-b border-border pb-3">
                <SearchInput value={search} onChange={setSearch} placeholder="Search..." className="max-w-md" />

                <div className="flex items-center gap-1.5">
                    {["all", "open", "in_progress", "blocked", "done"].map((status) => (
                        <button
                            key={status}
                            onClick={() => setStatusFilter(status)}
                            className={`rounded-xl px-3 py-1.5 text-xs font-mono font-bold uppercase transition-all ${
                                statusFilter === status
                                    ? "bg-primary text-primary-foreground shadow-md"
                                    : "border border-border bg-surface text-muted-foreground hover:bg-muted/50"
                            }`}
                        >
                            {status}
                        </button>
                    ))}
                </div>
            </div>

            {/* Task List */}
            {isLoading ? (
                <div className="rounded-2xl border border-border bg-surface p-6 text-xs text-muted-foreground animate-pulse">
                    Loading tasks from backend API...
                </div>
            ) : (
                <div className="space-y-3">
                    {filtered.map((task) => (
                        <div key={task.id} className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 rounded-2xl border border-border bg-surface p-4 shadow-sm hover:border-primary/40 transition-all">
                            <div className="space-y-1">
                                <div className="flex items-center gap-2">
                                    <h4 className="text-xs font-bold text-foreground">{task.title}</h4>
                                    <span className={`rounded-full px-2.5 py-0.5 font-mono text-xs font-bold border ${getPriorityBadge(task.priority)}`}>
                                        {task.priority}
                                    </span>
                                </div>
                                {task.description && (
                                    <p className="text-xs text-muted-foreground leading-relaxed line-clamp-1">{task.description}</p>
                                )}
                            </div>

                            <div className="flex items-center gap-3">
                                <span className="rounded-xl bg-muted px-3 py-1 font-mono text-xs font-bold text-foreground">
                                    {task.status}
                                </span>
                                {task.due_date && (
                                    <div className="flex items-center gap-1 font-mono text-xs text-muted-foreground">
                                        <Clock className="h-3.5 w-3.5" />
                                        <span>{task.due_date}</span>
                                    </div>
                                )}
                            </div>
                        </div>
                    ))}
                </div>
            )}
        </div>
    );
}
